import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const output = await build({
  entryPoints: [new URL("ui/app.ts", root).pathname],
  bundle: true,
  minify: true,
  write: false,
  format: "iife",
  target: "es2022",
});
const html = (await readFile(new URL("ui/index.html", root), "utf8")).replace(
  "/* BUNDLE */",
  () => output.outputFiles[0].text.replaceAll("</script", "<\\/script"),
);
await mkdir(new URL("src/generated/", root), { recursive: true });
await writeFile(
  new URL("src/generated/ui.ts", root),
  `// Generated by scripts/build-ui.mjs.\nexport default ${JSON.stringify(html)};\n`,
);
await mkdir(new URL("dist/", root), { recursive: true });
await writeFile(new URL("dist/ui.html", root), html);

// Fixture-only host for local visual verification; never embedded in the Worker resource.
await writeFile(new URL("dist/preview.html", root), await readFile(new URL("ui/preview.html", root)));

// Local preview uses the same Angular route, without changing the production resource.
await writeFile(new URL("dist/ui-preview.html", root), html.replaceAll("https://pkspot.app/embedded/results", "http://localhost:4300/de/embedded/results"));
