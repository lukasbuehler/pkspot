// @vitest-environment node
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { UserSchema } from "../../db/schemas/UserSchema";
import { BADGE_CATEGORIES } from "../shared/badge-definitions";
import { BadgeService } from "./badge.service";

/** Builds the smallest profile that earns exactly this category tier. */
function userEarning(
  category: (typeof BADGE_CATEGORIES)[number],
  tier: (typeof BADGE_CATEGORIES)[number]["tiers"][number],
): UserSchema {
  if (category.stat) {
    return { [category.stat]: tier.threshold } as UserSchema;
  }
  return { signup_number: tier.maxSignup } as UserSchema;
}

describe("BadgeService icons", () => {
  const service = new BadgeService();

  for (const category of BADGE_CATEGORIES) {
    for (const tier of category.tiers) {
      it(`ships a sticker for ${category.id} level ${tier.tier}`, () => {
        const badge = service
          .getDisplayBadges(userEarning(category, tier))
          .find((b) => b.category === category.id);

        expect(badge?.tier).toBe(tier.tier);
        expect(badge?.icon).toBe(
          `assets/badges/${category.iconPrefix}${tier.tier}.svg`,
        );

        // Generated by scripts/generate-badges.mjs.
        const file = resolve("src", badge!.icon);
        expect(existsSync(file)).toBe(true);
        expect(readFileSync(file, "utf8")).toMatch(/^<svg [^>]*viewBox=/u);
      });
    }
  }
});
